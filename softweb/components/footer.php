    $(document).ready(function() {
        const $modal = $('#termsPopup');
        const $popupBody = $('#popupBody');

        // Click handler invocation trigger 
        $('#openTerms').on('click', function(e) {
            e.preventDefault();

            const targetUrl = $(this).attr('href');

            $popupBody.html('<div class="modal-status-msg">Loading content...</div>');
            $modal.fadeIn(250);
            $('body').css('overflow', 'hidden'); // Lock background viewport track scrolling

            // AJAX loader injection process 
            $popupBody.load(targetUrl, function(response, status, xhr) {
                if (status === "error") {
                    $popupBody.html(
                        '<div class="modal-status-msg" style="color: #dc3545;">Failed to load the Terms & Conditions. Please try again.</div>'
                    );
                }
            });
        });

        // Close actions panel handling functions
        function closeTermsModal() {
            $modal.fadeOut(200, function() {
                $popupBody.empty(); // Release internal tracking memory properties
            });
            $('body').css('overflow', ''); // Normalizes background document scroll execution rules
        }

        $('.popup-close').on('click', closeTermsModal);

        $modal.on('click', function(e) {
            if ($(e.target).is($modal)) {
                closeTermsModal();
            }
        });

        $(document).on('keydown', function(e) {
            if (e.key === 'Escape' && $modal.is(':visible')) {
                closeTermsModal();
            }
        });
    });
    </script>
