            let currentTourIndex = 0;
            let isFullscreen = false;

            function openMap(index) {
                currentTourIndex = index;
                const container = document.getElementById("mapContainer");
                const iframe = document.getElementById("mapIframe");
                const loading = document.getElementById("loading");
                const tourName = document.getElementById("currentTourName");

                tourName.textContent = tours[index].name;

                loading.style.display = "flex";
                container.style.display = "block";

                setTimeout(() => {
                    iframe.src = tours[index].url;
                    loading.style.display = "none";
                    if (container.requestFullscreen) {
                        container.requestFullscreen();
                        isFullscreen = true;
                    } else if (container.webkitRequestFullscreen) {
                        container.webkitRequestFullscreen();
                        isFullscreen = true;
                    } else if (container.msRequestFullscreen) {
                        container.msRequestFullscreen();
                        isFullscreen = true;
                    }
                }, 100);
            }

            function closeMap() {
                const container = document.getElementById("mapContainer");
                const iframe = document.getElementById("mapIframe");
                container.style.animation = "fadeIn 0.3s reverse";
                setTimeout(() => {
                    iframe.src = "";
                    container.style.display = "none";
                    container.style.animation = "fadeIn 0.3s";
                }, 250);
                if (document.fullscreenElement || document.webkitFullscreenElement || document.msFullscreenElement) {
                    // Only try to exit fullscreen if currently in fullscreen
                    if (document.exitFullscreen) {
                        document.exitFullscreen();
                    } else if (document.webkitExitFullscreen) {
                        document.webkitExitFullscreen();
                    } else if (document.msExitFullscreen) {
                        document.msExitFullscreen();
                    }
                }
                isFullscreen = false; // Ensure this is reset when exiting fullscreen
            }

            function nextTour() {
                currentTourIndex = (currentTourIndex + 1) % tours.length;
                openMap(currentTourIndex);
            }

            function prevTour() {
                currentTourIndex = (currentTourIndex - 1 + tours.length) % tours.length;
                openMap(currentTourIndex);
            }

            // The toggleFullscreen function is not directly used for closing based on the user's request
            // but is kept as it was part of the original script.
            function toggleFullscreen() {
                const container = document.getElementById("mapContainer");
                if (!isFullscreen) {
                    if (container.requestFullscreen) {
                        container.requestFullscreen();
                    } else if (container.webkitRequestFullscreen) {
                        container.webkitRequestFullscreen();
                    } else if (container.msRequestFullscreen) {
                        container.msRequestFullscreen();
                    }
                    isFullscreen = true;
                } else {
                    if (document.exitFullscreen) {
                        document.exitFullscreen();
                    } else if (document.webkitExitFullscreen) {
                        document.webkitExitFullscreen();
                    } else if (document.msExitFullscreen) {
                        document.msExitFullscreen();
                    }
                    isFullscreen = false;
                }
            }

            // Listen for the Escape key press to close the map
            document.addEventListener('keydown', function(e) {
                if (e.key === "Escape") {
                    // If the map container is visible, close it
                    if (document.getElementById("mapContainer").style.display === "block") {
                        closeMap();
                    }
                }
                // Also handle arrow keys for navigation when the map is open
                if (document.getElementById("mapContainer").style.display === "block") {
                    if (e.key === "ArrowRight") {
                        nextTour();
                    } else if (e.key === "ArrowLeft") {
                        prevTour();
                    }
                }
            });

            // Listen for fullscreen change events to update the isFullscreen flag
            // and explicitly close the map if fullscreen is exited.
            const mapContainer = document.getElementById("mapContainer"); // Get this once
            document.addEventListener('fullscreenchange', () => {
                const wasFullscreenBeforeEvent =
                    isFullscreen; // Capture the state *before* updating based on the event
                isFullscreen = !!document.fullscreenElement; // Update the flag based on browser state

                // If it *was* fullscreen (according to our flag) and now it's not (according to browser),
                // and the map container is currently displayed, then the user exited fullscreen.
                // In this case, we explicitly call closeMap() to reset the map display.
                if (wasFullscreenBeforeEvent && !isFullscreen && mapContainer.style.display === "block") {
                    closeMap();
                }
            });
            document.addEventListener('webkitfullscreenchange', () => {
                const wasFullscreenBeforeEvent = isFullscreen;
                isFullscreen = !!document.webkitFullscreenElement;
